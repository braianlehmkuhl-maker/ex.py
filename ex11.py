#Objetivo: O maior de dois

#aqui o sistema ve oque o usuário escreve
n1 = int(input("Digite um número inteiro:"))
n2 = int(input("Digite outro número inteiro:"))

#aqui os sistem ve qual é maior e mostra o maior ao usuário
if n1>n2:
    print(f"O maior número é {n1}")
else:
    print(f"O maior número é {n2}")